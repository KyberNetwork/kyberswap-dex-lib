func TestYieldBasisPolicyFeeMatchesChain(t *testing.T) {
	for _, tc := range ybPolicyCases {
		sim := ybPolicySim(t, func(e *Extra) {
			e.Policy.ReportPrice = uint256.MustFromDecimal(tc.price)
			e.Policy.ReportObsUs = ybPolicyBlockTs*1_000_000 - tc.ageUs
		})
		require.Equal(t, tc.want, ybPolicyQuote(t, sim, tc.dir, tc.amt), "dir=%d amt=%s price=%s age=%d", tc.dir, tc.amt, tc.price, tc.ageUs)
	}
}

// A discount must differ from the flat fallback quote, or the test would pass without the port.
func TestYieldBasisPolicyDiscountBeatsFallback(t *testing.T) {
	disc := ybPolicySim(t, func(e *Extra) {
		e.Policy.ReportPrice = uint256.MustFromDecimal("2228414323008129201419")
		e.Policy.ReportObsUs = ybPolicyBlockTs*1_000_000 - 60_000_000
	})
	flat := ybPolicySim(t, func(e *Extra) { e.Policy = nil; e.PolicyFee = uint256.NewInt(175000000) })
	require.Equal(t, "3214408766496035351", ybPolicyQuote(t, disc, 0, "7234489014963216359320"))
	require.Equal(t, "3191960012245233840", ybPolicyQuote(t, flat, 0, "7234489014963216359320"))
}

