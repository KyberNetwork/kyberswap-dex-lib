// A swap after a quote changes the snapshot: a following swap in the same direction sees the new
// xp and D, as the policy does after update_pool_state.
func TestYieldBasisPolicyUpdateBalanceMovesSnapshot(t *testing.T) {
	sim := ybPolicySim(t, func(*Extra) {})
	before := sim.Extra.Policy.SnapXp
	res, err := sim.CalcAmountOut(poolpkg.CalcAmountOutParams{
		TokenAmountIn: poolpkg.TokenAmount{Token: ybCrvUSD, Amount: bigFrom("7234489014963216359320")}, TokenOut: ybWETH,
	})
	require.NoError(t, err)
	sim.UpdateBalance(poolpkg.UpdateBalanceParams{
		TokenAmountIn:  poolpkg.TokenAmount{Token: ybCrvUSD, Amount: bigFrom("7234489014963216359320")},
		TokenAmountOut: *res.TokenAmountOut, Fee: *res.Fee, SwapInfo: res.SwapInfo,
	})
	require.NotEqual(t, before, sim.Extra.Policy.SnapXp)
	require.True(t, sim.Extra.Policy.SnapD.Eq(sim.Extra.D))
}

func TestPolicyFetchRejectsUnknown(t *testing.T) {
	// A policy with unverified logic is rejected before any RPC call.
	_, err := FetchPolicy(context.Background(), nil, nil, common.HexToAddress("0x57336cE442165ccDF19a820355a823238137170b"), nil)
	require.ErrorIs(t, err, ErrUnsupportedPolicy)
	// A verified native-fee policy (get_fee returns 0) keeps the pool's own fee.
	st, err := FetchPolicy(context.Background(), nil, nil, common.HexToAddress("0x0436c0648AfD66de23f86f23cB42884304743EfA"), nil)
	require.NoError(t, err)
	require.Nil(t, st)
}

