// Yield Basis WETH pool 0x656341Ef...b9f3 (YBOraclizedPolicy 0xAEa95d55...8A7d) at ethereum block
// 26357025 (timestamp 1793982731), 4 blocks after a ReportAccepted (report observed 10s before the
// block). Expected dy values are policy.get_dy_with_report_age(i, j, dx, price, age_us) and
// pool.get_dy at that block, from an archive node. Overrides use eth_call state overrides.
const (
	ybPolicyBlockTs   = 1793982731
	ybPolicyExtraJSON = `{"InitialA":"50000","InitialGamma":"11111111111","FutureA":"50000","FutureGamma":"11111111111","FutureAGammaTime":0,"D":"28920992518852715006659095","PriceScale":["2226188134873255945474"],"PriceOracle":["2227095218809502428381"],"LastPrices":["2226158574976602507712"],"FeeGamma":"4961947600000000","MidFee":"136000000","OutFee":"282000000","LpSupply":"290330660372526420093312","XcpProfit":"1098929110208888044","VirtualPrice":"1055624262909313732","AllowedExtraProfit":null,"AdjustmentStep":"100000000","UseCustomMath":true,"Policy":{"BaseFee":"50000000","Capture":"675000000000000000","FallbackFee":"175000000","RelaxTime":300,"ReportPrice":"2232920023310000000000","ReportObsUs":1793982721000000,"CachedA":"50000","SnapXp":["14468978029926432718640160","14452015318005896232381623"],"SnapD":"28920992518852715006659095","SnapPriceScl":"2226188134873255945474"}}`
)

func ybPolicySim(t *testing.T, mutate func(*Extra)) *PoolSimulator {
	old := policyClockSec
	policyClockSec = func() uint64 { return ybPolicyBlockTs }
	t.Cleanup(func() { policyClockSec = old })

	var extra Extra
	require.NoError(t, json.Unmarshal([]byte(ybPolicyExtraJSON), &extra))
	mutate(&extra)
	extraBytes, err := json.Marshal(extra)
	require.NoError(t, err)
	sim, err := NewPoolSimulator(entity.Pool{
		Address: "0x656341ef90b622c6634e0573772ffb7f3669b9f3", Exchange: "curve-twocrypto-ng", Type: DexType,
		Reserves: []string{"14468978029926432718640160", "6491821194990196087759"},
		Tokens: []*entity.PoolToken{
			{Address: ybCrvUSD, Decimals: 18, Swappable: true}, {Address: ybWETH, Decimals: 18, Swappable: true},
		},
		Extra: string(extraBytes), StaticExtra: `{"IsNativeCoins":[false,false]}`,
	})
	require.NoError(t, err)
	return sim
}

func ybPolicyQuote(t *testing.T, sim *PoolSimulator, dir int, amt string) string {
	tokens := []string{ybCrvUSD, ybWETH}
	res, err := sim.CalcAmountOut(poolpkg.CalcAmountOutParams{
		TokenAmountIn: poolpkg.TokenAmount{Token: tokens[dir], Amount: bigFrom(amt)}, TokenOut: tokens[1-dir],
	})
	require.NoError(t, err)
	return res.TokenAmountOut.Amount.String()
}

