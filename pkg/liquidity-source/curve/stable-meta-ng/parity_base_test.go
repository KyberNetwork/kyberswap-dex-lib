// parityBasePools builds the base pool map keyed by address, as the factory does.
func parityBasePools(t *testing.T) map[string]pool.IPoolSim {
	t.Helper()
	out := make(map[string]pool.IPoolSim, len(parityBasePoolJSON))
	for _, raw := range parityBasePoolJSON {
		var e entity.Pool
		require.NoError(t, json.Unmarshal([]byte(raw), &e))
		switch e.Exchange {
		case stableng.DexType:
			p, err := stableng.NewPoolSimulator(e)
			require.NoError(t, err)
			out[e.Address] = p
		case plain.DexType:
			p, err := plain.NewPoolSimulator(e)
			require.NoError(t, err)
			out[e.Address] = p
		}
	}
	return out
}
